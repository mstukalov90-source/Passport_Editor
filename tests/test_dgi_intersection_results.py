@pytest.mark.django_db
def test_list_dgi_intersections_api_ok(client: Client):
    if not _results_table_ready():
        pytest.skip(f"{RESULTS_TABLE} missing (migrate first)")

    # Client request imports middleware/views (needs Python 3.10+ / GDAL env).
    try:
        from pass_viewer import views as _views  # noqa: F401
    except Exception as exc:
        pytest.skip(f"views unavailable in this env: {exc}")

    with connection.cursor() as cursor:
        cursor.execute(f"TRUNCATE TABLE {RESULTS_TABLE} RESTART IDENTITY")
    _insert_result(owner_legal_person_id="OWNER_API", rootid="API-1", pct_sum=0.76)

    ExternalUser.objects.create(
        login="api_dgi_user",
        password="pass",
        owner_legal_person_id="OWNER_API",
        role=ROLE_BD,
    )
    user = User.objects.create_user(username="api_dgi_user", password="pass")
    client.force_login(user)

    response = client.get("/owned/dgi-intersections/")
    assert response.status_code == 200
    data = response.json()
    assert data["ok"] is True
    assert len(data["rows"]) == 1
    assert data["rows"][0]["rootid"] == "API-1"
    assert data["rows"][0]["pct_sum"] == 0.76
    assert "modal" in data["rows"][0]
    assert data["calculated_at"]
