def _ensure_results_table():
    """Apply CREATE TABLE if migration 0029 is not on this DB yet."""
    with connection.cursor() as cursor:
        cursor.execute(
            """
            CREATE TABLE IF NOT EXISTS dgi_intersection_results (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                table_name text NOT NULL,
                source_label text NOT NULL,
                object_kind text NOT NULL,
                rootid text NULL,
                request_id text NULL,
                name text NULL,
                owner_legal_person_id text NULL,
                pct_moscow_rent numeric(8,2) NOT NULL DEFAULT 0,
                pct_private_rent numeric(8,2) NOT NULL DEFAULT 0,
                pct_private_no_rent numeric(8,2) NOT NULL DEFAULT 0,
                pct_sum numeric(8,2) NOT NULL DEFAULT 0,
                pct_moscow_no_rent numeric(8,2) NOT NULL DEFAULT 0,
                pct_renew numeric(8,2) NOT NULL DEFAULT 0,
                pct_oozt numeric(8,2) NOT NULL DEFAULT 0,
                pct_rzd numeric(8,2) NOT NULL DEFAULT 0,
                calculated_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT dgi_intersection_results_kind_chk
                    CHECK (object_kind IN ('passport', 'request'))
            )
            """
        )


def _results_table_ready() -> bool:
    try:
        _ensure_results_table()
    except Exception:
        return False
    with connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT EXISTS (
                SELECT 1 FROM information_schema.tables
                WHERE table_schema = 'public' AND table_name = %s
            )
            """,
            [RESULTS_TABLE],
        )
        return bool(cursor.fetchone()[0])


def _insert_result(
    *,
    table_name="pass_objects",
    source_label="ДТ",
    object_kind="passport",
    rootid="ROOT-A",
    request_id=None,
    name="Obj A",
    owner_legal_person_id="OWNER_A",
    pct_sum=1.5,
):
    with connection.cursor() as cursor:
        cursor.execute(
            f"""
            INSERT INTO {RESULTS_TABLE} (
                table_name, source_label, object_kind, rootid, request_id, name,
                owner_legal_person_id,
                pct_moscow_rent, pct_private_rent, pct_private_no_rent, pct_sum,
                pct_moscow_no_rent, pct_renew, pct_oozt, pct_rzd, calculated_at
            ) VALUES (
                %s, %s, %s, %s, %s, %s, %s,
                %s, 0, 0, %s, 0, 0, 0, 0, %s
            )
            """,
            [
                table_name,
                source_label,
                object_kind,
                rootid,
                request_id,
                name,
                owner_legal_person_id,
                pct_sum,
                pct_sum,
                dj_timezone.now(),
            ],
        )


@pytest.mark.django_db
def test_list_dgi_intersection_results_filters_by_owner():
    if not _results_table_ready():
        pytest.skip(f"{RESULTS_TABLE} missing (migrate first)")

    with connection.cursor() as cursor:
        cursor.execute(f"TRUNCATE TABLE {RESULTS_TABLE} RESTART IDENTITY")

    _insert_result(owner_legal_person_id="OWNER_A", rootid="A1", pct_sum=2.0)
    _insert_result(owner_legal_person_id="OWNER_B", rootid="B1", pct_sum=9.0)

    ExternalUser.objects.create(
        login="bd_dgi", password="pass", owner_legal_person_id="OWNER_A", role=ROLE_BD
    )
    scope = resolve_user_scope("bd_dgi")
    rows = list_dgi_intersection_results_for_scope(scope, has_sup_hood=False)
    assert len(rows) == 1
    assert rows[0]["rootid"] == "A1"
    assert rows[0]["pct_sum"] == 2.0


